package com.careerit;

import java.util.Scanner;

public class Switch {
    public static void main(String[] args) {
        int i=4;
        switch(i){
            case 1:
                System.out.println("This is the data");
                break;
                case 2:
                    System.out.println("This is the second data");
                    break;
                    case 3:
                        System.out.println("this is the third data");
                        break;
                        case 4:
                            System.out.println("this is the fourth data");
                            break;
                            default:
                                System.out.println("This is the default data");
                                break;

        }
    }

}
